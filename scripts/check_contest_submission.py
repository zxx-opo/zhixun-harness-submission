"""Local JSONL host stand-in. Real CPU fits and public scoring, simulated model receipts."""
import argparse
import base64
import json
import os
from pathlib import Path
import select
import signal
import subprocess
import tempfile
from time import monotonic

import numpy as np

from contest_engine.model import ACTIONS, EXTENSION, NATIVE, TASKS, load, sha256_file, source_rows


ROOT = Path(__file__).resolve().parents[1]
REF = ROOT / "vendor/reference"
IMAGE = "zhixun-harness:contest-1.0.2"
PROTOCOL = "contest.harness.workspace.v2"
PROMPT = "Official prompt placeholder generated by the local host stand-in."
ARGV = ["python3", "/app/harness.py", "predict"]
CLASSIFY = "classification"


def stable(value):
    return json.dumps(value, sort_keys=True, allow_nan=False, separators=(",", ":")).encode()


def send(process, value):
    process.stdin.write(stable(value).decode() + "\n")
    process.stdin.flush()


def run_command(image, subcommand, mounts=(), env=None):
    cmd = ["docker", "run", "--rm", "-i", "--network=none", "--read-only", "--cpus=4", "--memory=8g",
           "--pids-limit=256", "--tmpfs", "/workspace:rw,size=256m,uid=65534,gid=65534,mode=0700",
           "--tmpfs", "/tmp:rw,size=64m"]
    for source, dest in mounts:
        cmd.extend(("-v", f"{source}:{dest}:ro"))
    for key, value in (env or {}).items():
        cmd.extend(("-e", f"{key}={value}"))
    return [*cmd, image, subcommand]


def manifest(folder, artifact_id, paths):
    files = [{"path": name, "sha256": sha256_file(folder / name), "size_bytes": (folder / name).stat().st_size}
             for name in paths]
    return {"artifact_id": artifact_id, "artifact": {"checkpoint_paths": paths, "code_paths": [], "predict_argv": ARGV},
            "files": files}


def files_from_frame(entries, directory):
    directory.mkdir()
    for entry in entries:
        assert entry["path"] in (NATIVE, EXTENSION, "memory.json")
        path = directory / entry["path"]
        assert not path.exists()
        path.write_bytes(base64.b64decode(entry["data_base64"], validate=True))
    return directory


def validation_metrics(dataset, expected, outputs):
    if dataset == "A":
        labels = outputs.argmax(axis=1)
        tp = np.bincount(expected[labels == expected], minlength=6)
        denominator = np.bincount(expected, minlength=6) + np.bincount(labels, minlength=6)
        f1 = np.divide(2 * tp, denominator, out=np.zeros(6), where=denominator > 0)
        return {"macro_f1": float(f1.mean()), "accuracy": float(np.mean(labels == expected))}
    residual = outputs - expected
    result = {"rmse": float(np.sqrt(np.mean(residual ** 2))), "mae": float(np.mean(np.abs(residual)))}
    if dataset == "C":
        result["nasa_score"] = float(np.expm1(np.where(residual < 0, -residual / 13, residual / 10)).sum())
    return result


def simulator(facts, tick):
    if tick == 2:
        return "{ invalid JSON fixture"
    choices = ACTIONS[facts["dataset"]]
    selection = "child" if facts["eligible_child"] or tick == 3 else "parent"
    return json.dumps({"selection": selection, "next_action": choices[tick % len(choices)], "reason": "local fixture"})


def predict_one(image, dataset, folder, artifact, sample, expected):
    task = TASKS[dataset]
    context = {"protocol": "contest.predict-context.v1", "task": task, "dataset_key": dataset,
               "artifact": artifact["artifact"], "artifact_id": artifact["artifact_id"]}
    env = {"CONTEST_PREDICTION_CONTEXT": stable(context).decode(), "CONTEST_ARTIFACT_PATH": f"/model/{NATIVE}",
           "CONTEST_DATASET_KEY": dataset, "CONTEST_TASK": task}
    cmd = run_command(image, "predict", [(folder, "/model")], env)
    with subprocess.Popen(cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True) as proc:
        send(proc, {"task": task, "inputs": sample})
        if not select.select([proc.stdout], [], [], 40)[0]:
            proc.kill()
            raise RuntimeError("prediction did not respond before EOF")
        line = proc.stdout.readline()
        if not line:
            raise RuntimeError(proc.stderr.read())
        outputs = json.loads(line)["outputs"]
        values = [item["score"] for item in outputs] if task == CLASSIFY else outputs["value"]
        np.testing.assert_allclose(values, expected, rtol=1e-11, atol=1e-11)
        proc.stdin.close()
        assert proc.wait(timeout=10) == 0, proc.stderr.read()


def check_dataset(image, dataset, rounds, base, output):
    begin = monotonic()
    official = REF / dataset
    original = official / NATIVE
    task = TASKS[dataset]
    metric = "macro_f1" if dataset == "A" else "rmse"
    baseline = load(original, dataset=dataset)
    validation = official / "public/validation.jsonl"
    with validation.open(encoding="utf-8") as stream:
        sample = json.loads(next(stream))["inputs"]
        stream.seek(0)
        x, y = source_rows((json.loads(line) for line in stream if line.strip()), baseline.native)
    parent_folder = official
    parent = manifest(parent_folder, f"baseline-{dataset}", [NATIVE])
    state_dir, state_sha = None, None
    history, all_artifacts = [], []
    score = validation_metrics(dataset, y, baseline.predict(x))
    result = {"baseline": score, "validation_rows": len(y), "rounds": history, "accepted": 0,
              "candidate_measurements": 0, "real_local_candidate_fits": 0, "simulated_calls": 0}
    predict_one(image, dataset, parent_folder, parent, sample, baseline.predict(x[:1])[0])
    for tick in range(1, rounds + 1):
        wall = monotonic()
        frame = {"protocol": PROTOCOL, "prompt": PROMPT, "prompt_version": "industrial-workspace-flexible-v3",
                 "dataset_key": dataset, "round_index": tick, "stage_id": "reused_public_projection",
                 "task_contract": {"task": task, "metric": metric, "public_projection": {
                     "train_path": "/data/train.jsonl", "validation_path": "/data/validation.jsonl"}},
                 "model_name": "Qwen/Qwen3.8-27B", "max_output_tokens": 256, "wall_seconds": 240,
                 "parent_checkpoint_sha256": parent["files"][0]["sha256"], "parent_artifact": parent,
                 "artifacts": all_artifacts, "state_path": "/state" if state_dir else None, "state_sha256": state_sha}
        mounts = [(official / "public", "/data"), (parent_folder, "/previous")]
        if state_dir is not None:
            mounts.append((state_dir, "/state"))
        artifacts = {}
        next_state = state_dir
        requested, checks = [], []
        cmd = run_command(image, "train", mounts)
        with tempfile.TemporaryFile(mode="w+", encoding="utf-8") as log, subprocess.Popen(
            cmd, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=log, text=True,
        ) as proc:
            try:
                signal.alarm(240)
                send(proc, frame)
                sequence = 0
                for text in proc.stdout:
                    msg = json.loads(text)
                    kind = msg["type"]
                    requested.append(kind)
                    if kind == "round_failed":
                        raise RuntimeError(msg["error"])
                    if kind == "round_complete":
                        record = msg["record"]
                        assert record["history_ids"] == [item["id"] for item in history]
                        assert record["model_call_ids"] == [f"mock-{dataset}-{tick}"]
                        selected = record["selected_artifact_id"]
                        if selected != parent["artifact_id"]:
                            parent_folder, parent, score = artifacts[selected]
                            result["accepted"] += 1
                        assert tick != 2 or (record["configuration"]["proposal"] is None and record["configuration"]["selection"] == "kept_parent")
                        send(proc, {"type": "round_ack", "accepted": True})
                        break
                    assert msg["id"] == sequence
                    sequence += 1
                    if kind == "history_request":
                        reply = {"type": "history_response", "records": history}
                    elif kind == "candidate_request":
                        assert msg["parent_artifact_id"] == parent["artifact_id"]
                        assert msg["parent_checkpoint_sha256"] == parent["files"][0]["sha256"]
                        identity = f"{dataset}-{tick}-{len(artifacts)}"
                        folder = files_from_frame(msg["files"], base / identity)
                        spec = msg["artifact"]
                        assert spec["predict_argv"] == ARGV and spec["code_paths"] == []
                        current = manifest(folder, identity, spec["checkpoint_paths"])
                        predictor = load(folder / NATIVE, folder / EXTENSION if (folder / EXTENSION).is_file() else None, dataset)
                        measured = validation_metrics(dataset, y, predictor.predict(x))
                        previous_model = load(parent_folder / NATIVE, dataset=dataset).native
                        for field in ("target_mean", "target_scale", "paths", "seed"):
                            assert predictor.native.meta[field] == previous_model.meta[field]
                        np.testing.assert_array_equal(predictor.native.mean, previous_model.mean)
                        np.testing.assert_array_equal(predictor.native.scale, previous_model.scale)
                        recipe = msg["configuration"].get("recipe", {})
                        if not recipe.get("steps"):
                            assert current["files"][0]["sha256"] == parent["files"][0]["sha256"]
                        else:
                            assert predictor.native.meta["steps"] - previous_model.meta["steps"] == recipe["steps"]
                        if not artifacts:
                            assert measured == score and msg["configuration"]["role"] == "paired_parent"
                        else:
                            result["real_local_candidate_fits"] += 1
                            if not checks and tick in (1, 2, rounds):
                                checks.append((folder, current, predictor.predict(x[:1])[0]))
                        result["candidate_measurements"] += 1
                        artifacts[identity] = folder, current, measured
                        reply = {"type": "candidate_response", "artifact_id": identity, "summary": {"metrics": measured}}
                    elif kind == "model_request":
                        assert len(artifacts) in (0, 2) and PROMPT not in json.dumps(msg["messages"])
                        assert 0 < msg["max_tokens"] <= 224
                        facts = json.loads(msg["messages"][-1]["content"])
                        if len(artifacts) == 2:
                            anchor, child = (value[2] for value in artifacts.values())
                            assert facts["paired_parent"][metric] == anchor[metric] and facts["child"][metric] == child[metric]
                        result["simulated_calls"] += 1
                        reply = {"type": "model_response", "call_id": f"mock-{dataset}-{tick}",
                                 "response": {"choices": [{"message": {"content": simulator(facts, tick)}}]}}
                    elif kind == "state_request":
                        assert msg["parent_state_sha256"] == (state_sha or "")
                        next_state = files_from_frame(msg["files"], base / f"state-{dataset}-{tick}")
                        state_sha = sha256_file(next_state / "memory.json")
                        reply = {"type": "state_response", "state_sha256": state_sha}
                    else:
                        raise ValueError(kind)
                    send(proc, {**reply, "id": msg["id"]})
                else:
                    raise RuntimeError("participant stopped without round_complete")
                proc.stdin.close()
                assert proc.wait(timeout=15) == 0 and not proc.stdout.read()
                assert requested[0] == "history_request" and requested[-1] == "round_complete"
                assert requested.index("model_request") < requested.index("state_request")
            except BaseException:
                log.seek(0)
                print(log.read(), flush=True)
                if proc.poll() is None:
                    proc.kill()
                raise
            finally:
                signal.alarm(0)
        state_dir = next_state
        for folder, artifact, pred in checks:
            predict_one(image, dataset, folder, artifact, sample, pred)
        history.append({**record, "id": f"history-{dataset}-{tick}", "trace": requested, "wall_seconds": monotonic() - wall,
                        "selected_metrics": score})
        all_artifacts.extend(value[1] for value in artifacts.values())
        output.write_text(json.dumps(result, indent=2, allow_nan=False), encoding="utf-8")
        print(f"{dataset} {tick}/{rounds} {record['configuration']['selection']} {metric}={score[metric]:.6f}", flush=True)
    result["final"] = score
    result["elapsed_seconds"] = monotonic() - begin
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--tasks", default="ABC")
    parser.add_argument("--rounds", type=int, default=10)
    parser.add_argument("--image", default=IMAGE)
    args = parser.parse_args()
    signal.signal(signal.SIGALRM, fail_on_timeout)
    inspect = json.loads(subprocess.check_output(["docker", "image", "inspect", args.image], text=True))[0]
    description = json.loads(subprocess.check_output(run_command(args.image, "describe"), text=True))
    assert description["protocol"] == PROTOCOL and description["model_access"] == "host_gateway_rpc"
    assert description["sdk_version"] == "1.0.2" and set(description["tasks"]) == {"classification", "regression"}
    assert inspect["Architecture"] == "amd64" and inspect["Os"] == "linux"
    out = ROOT / "reports/contest-submission"
    out.mkdir(parents=True, exist_ok=True)
    tasks = {}
    # A single directory is shared with the local Docker daemon through read-only mounts.
    with tempfile.TemporaryDirectory(prefix="zhixun-contest-host-") as location:
        base = Path(location)
        os.chmod(base, 0o755)
        for dataset in args.tasks:
            tasks[dataset] = check_dataset(args.image, dataset, args.rounds, base, out / f"acceptance-{dataset}.json")
    result = {"passed": True, "scope": "local public host stand-in with simulated model RPCs", "image_id": inspect["Id"],
              "image_bytes": inspect["Size"], "describe": description, "runs": tasks,
              "network": "none", "cpus": 4, "memory_gib": 8, "readonly_mounts": True}
    (out / "local-acceptance.json").write_text(json.dumps(result, indent=2, allow_nan=False), encoding="utf-8")


def fail_on_timeout(*_):
    raise TimeoutError("local round timed out")


if __name__ == "__main__":
    main()
